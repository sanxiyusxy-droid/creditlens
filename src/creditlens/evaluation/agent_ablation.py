class AblationScenario(_StrictModel):
    scenario_id: str
    description: str = Field(min_length=1)
    unsupported_claim_ids: list[str] = Field(default_factory=list)
    counter_evidence_target_ids: list[str] = Field(default_factory=list)
    tags: list[str] = Field(default_factory=list)
    component_harness: ComponentHarnessFixture

    @field_validator("scenario_id")
    @classmethod
    def validate_scenario_id(cls, value: str) -> str:
        value = value.strip()
        if not value:
            raise ValueError("scenario_id must not be blank")
        return value

    @model_validator(mode="after")
    def validate_label_ids(self) -> Self:
        if len(set(self.unsupported_claim_ids)) != len(self.unsupported_claim_ids):
            raise ValueError("unsupported_claim_ids must be unique")
        if len(set(self.counter_evidence_target_ids)) != len(self.counter_evidence_target_ids):
            raise ValueError("counter_evidence_target_ids must be unique")
        expected_unsupported = set(self.component_harness.expected_contract_violation_substrings)
        if expected_unsupported != set(self.unsupported_claim_ids):
            raise ValueError(
                "component_harness contract labels must exactly match unsupported_claim_ids"
            )
        expected_counter = {item.target_id for item in self.component_harness.counter_evidence}
        if len(expected_counter) != len(self.component_harness.counter_evidence):
            raise ValueError("component_harness counter target IDs must be unique")
        if expected_counter != set(self.counter_evidence_target_ids):
            raise ValueError(
                "component_harness counter labels must exactly match counter_evidence_target_ids"
            )
        return self


class AgentAblationDataset(_StrictModel):
    protocol_id: Literal["creditlens_multi_agent_ablation_v1"]
    protocol_version: Literal["1.0.0"]
    frozen: Literal[True]
    variants: list[AblationVariantDefinition]
    scenarios: list[AblationScenario] = Field(min_length=1)

    @field_validator("frozen", mode="before")
    @classmethod
    def validate_frozen(cls, value):
        if value is not True:
            raise ValueError("frozen must be exactly true")
        return value

    @model_validator(mode="after")
    def validate_matrix_definition(self) -> Self:
        variants = [item.variant for item in self.variants]
        if len(set(variants)) != len(variants):
            raise ValueError("ablation variants must be unique")
        if set(variants) != set(AblationVariant):
            raise ValueError("all four frozen ablation variants are required")
        if {item.execution_semantics for item in self.variants} != {
            ExecutionSemantics.DETERMINISTIC_COMPONENT_HARNESS
        }:
            raise ValueError("all variants must use DETERMINISTIC_COMPONENT_HARNESS semantics")
        scenario_ids = [item.scenario_id for item in self.scenarios]
        if len(set(scenario_ids)) != len(scenario_ids):
            raise ValueError("ablation scenario IDs must be unique")
        return self


class AblationTrialObservation(_StrictModel):
    scenario_id: str
    variant: AblationVariant
    execution_semantics: ExecutionSemantics
    source_run_id: uuid.UUID
    source_artifact_path: str
    source_artifact_sha256: str
    recorded_at: datetime
    unsupported_claim_ids_emitted: list[str] = Field(default_factory=list)
    unsupported_claim_ids_intercepted: list[str] = Field(default_factory=list)
    counter_evidence_target_ids_found: list[str] = Field(default_factory=list)
    hitl_triggered: bool
    latency_ms: float = Field(ge=0)
    total_tokens: None = None
    estimated_cost: None = None
    cost_currency: None = None
    terminal_status: Literal[
        "COMPLETED",
        "HUMAN_REVIEW",
        "FAILED",
        "NEED_MORE_INFO",
        "DATA_QUALITY_BLOCKED",
    ]

    @field_validator("source_artifact_sha256")
    @classmethod
    def validate_source_hash(cls, value: str) -> str:
        normalized = value.strip().lower()
        if len(normalized) != 64 or any(
            character not in "0123456789abcdef" for character in normalized
        ):
            raise ValueError("source_artifact_sha256 must be a lowercase SHA-256 digest")
        return normalized

    @field_validator("source_artifact_path")
    @classmethod
    def validate_source_artifact_path(cls, value: str) -> str:
        candidate = PurePosixPath(value.strip())
        if (
            not value.strip()
            or candidate.is_absolute()
            or ".." in candidate.parts
            or candidate.suffix != ".json"
            or candidate.as_posix() != value.strip()
        ):
            raise ValueError("source_artifact_path must be a normalized relative POSIX JSON path")
        return candidate.as_posix()

    @field_validator("recorded_at")
    @classmethod
    def validate_recorded_at(cls, value: datetime) -> datetime:
        if value.tzinfo is None or value.utcoffset() is None:
            raise ValueError("recorded_at must include a timezone")
        return value

    @field_validator(
        "unsupported_claim_ids_emitted",
        "unsupported_claim_ids_intercepted",
        "counter_evidence_target_ids_found",
    )
    @classmethod
    def validate_unique_ids(cls, values: list[str]) -> list[str]:
        if len(set(values)) != len(values):
            raise ValueError("observation IDs must be unique")
        return values

    @model_validator(mode="after")
    def validate_observation_contract(self) -> Self:
        if self.execution_semantics != ExecutionSemantics.DETERMINISTIC_COMPONENT_HARNESS:
            raise ValueError("only deterministic component harness observations are accepted")
        if not set(self.unsupported_claim_ids_intercepted) <= set(
            self.unsupported_claim_ids_emitted
        ):
            raise ValueError("intercepted unsupported claims must have been emitted")
        return self


class AgentAblationObservationSet(_StrictModel):
    observation_set_id: str = Field(min_length=1)
    protocol_id: Literal["creditlens_multi_agent_ablation_v1"]
    protocol_version: Literal["1.0.0"]
    observations: list[AblationTrialObservation]
    metadata: AblationObservationMetadata

    @model_validator(mode="after")
    def validate_unique_cells(self) -> Self:
        cells = [(item.scenario_id, item.variant) for item in self.observations]
        if len(set(cells)) != len(cells):
            raise ValueError("each scenario/variant cell may appear only once")
        run_ids = [item.source_run_id for item in self.observations]
        if len(set(run_ids)) != len(run_ids):
            raise ValueError("each scenario/variant cell requires a unique actual run UUID")
        artifact_paths = [item.source_artifact_path for item in self.observations]
        if len(set(artifact_paths)) != len(artifact_paths):
            raise ValueError("each scenario/variant cell requires a unique artifact sidecar")
        return self


