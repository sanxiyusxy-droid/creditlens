class AblationHarnessArtifact(_StrictModel):
    """Per-cell evidence sidecar generated by the offline component collector."""

    artifact_type: Literal["creditlens_agent_ablation_component_harness_v1"]
    protocol_id: Literal["creditlens_multi_agent_ablation_v1"]
    protocol_version: Literal["1.0.0"]
    collector_version: str = Field(min_length=1)
    scenario_id: str = Field(min_length=1)
    variant: AblationVariant
    execution_semantics: Literal[ExecutionSemantics.DETERMINISTIC_COMPONENT_HARNESS]
    source_run_id: uuid.UUID
    recorded_at: datetime
    disabled_components: list[str]
    challenger_enabled: bool
    auditor_enabled: bool
    input_artifact: AgentArtifact
    contract_validation: ContractValidationTrace
    conflict_assessments: list[ConflictAssessmentTrace]
    outcome: AblationHarnessOutcome
    measured_latency_ms: float = Field(ge=0)
    total_tokens: None = None
    estimated_cost: None = None
    cost_currency: None = None
    limitations: list[str] = Field(min_length=1)

    @field_validator("recorded_at")
    @classmethod
    def validate_recorded_at(cls, value: datetime) -> datetime:
        if value.tzinfo is None or value.utcoffset() is None:
            raise ValueError("recorded_at must include a timezone")
        return value

    @model_validator(mode="after")
    def validate_sidecar_consistency(self) -> Self:
        if self.input_artifact.run_id != self.source_run_id:
            raise ValueError("input_artifact run_id must match source_run_id")
        if self.contract_validation.component_enabled != self.auditor_enabled:
            raise ValueError("contract validation enablement must match Auditor")
        if not self.challenger_enabled and self.conflict_assessments:
            raise ValueError("disabled Challenger cannot expose conflict assessments")
        assessed_targets = [item.target_id for item in self.conflict_assessments]
        if len(set(assessed_targets)) != len(assessed_targets):
            raise ValueError("conflict assessment target IDs must be unique")
        if assessed_targets != self.outcome.counter_evidence_target_ids_found:
            raise ValueError("counter-evidence outcome must match executed assessments")
        if not self.auditor_enabled and self.outcome.unsupported_claim_ids_intercepted:
            raise ValueError("disabled Auditor cannot intercept unsupported claims")
        expected_hitl = self.auditor_enabled and bool(
            self.outcome.unsupported_claim_ids_intercepted
            or any(item.is_conflict for item in self.conflict_assessments)
        )
        if self.outcome.hitl_triggered != expected_hitl:
            raise ValueError("HITL outcome does not follow the frozen harness gate")
        expected_terminal = "HUMAN_REVIEW" if expected_hitl else "COMPLETED"
        if self.outcome.terminal_status != expected_terminal:
            raise ValueError("terminal status does not follow the frozen harness gate")
        return self


class AblationVariantMetrics(_StrictModel):
    variant: AblationVariant
    execution_semantics: Literal[ExecutionSemantics.DETERMINISTIC_COMPONENT_HARNESS]
    trials: Literal[6]
    unsupported_claims_emitted: int = Field(ge=0)
    unsupported_claims_intercepted: int = Field(ge=0)
    unsupported_claim_interception_rate: float | None = Field(default=None, ge=0, le=1)
    counter_evidence_targets: int = Field(ge=0)
    counter_evidence_targets_found: int = Field(ge=0)
    counter_evidence_recall: float | None = Field(default=None, ge=0, le=1)
    hitl_trials: int = Field(ge=0, le=6)
    hitl_rate: float = Field(ge=0, le=1)
    p95_latency_ms: float = Field(ge=0)
    total_tokens: int | None
    mean_tokens_per_trial: float | None
    token_coverage: float = Field(ge=0, le=1)
    estimated_cost: Decimal | None
    cost_currency: str | None
    cost_coverage: float = Field(ge=0, le=1)

    @model_validator(mode="after")
    def validate_metric_arithmetic(self) -> Self:
        if self.unsupported_claims_intercepted > self.unsupported_claims_emitted:
            raise ValueError("unsupported interceptions cannot exceed emitted claims")
        expected_unsupported_rate = (
            self.unsupported_claims_intercepted / self.unsupported_claims_emitted
            if self.unsupported_claims_emitted
            else None
        )
        if expected_unsupported_rate is None:
            if self.unsupported_claim_interception_rate is not None:
                raise ValueError("unsupported interception rate requires a non-zero denominator")
        elif self.unsupported_claim_interception_rate is None or not math.isclose(
            self.unsupported_claim_interception_rate,
            expected_unsupported_rate,
            rel_tol=0,
            abs_tol=1e-12,
        ):
            raise ValueError("unsupported interception rate does not match its counts")

        if self.counter_evidence_targets_found > self.counter_evidence_targets:
            raise ValueError("found counter evidence cannot exceed frozen targets")
        expected_counter_rate = (
            self.counter_evidence_targets_found / self.counter_evidence_targets
            if self.counter_evidence_targets
            else None
        )
        if expected_counter_rate is None:
            if self.counter_evidence_recall is not None:
                raise ValueError("counter-evidence recall requires a non-zero denominator")
        elif self.counter_evidence_recall is None or not math.isclose(
            self.counter_evidence_recall,
            expected_counter_rate,
            rel_tol=0,
            abs_tol=1e-12,
        ):
            raise ValueError("counter-evidence recall does not match its counts")

        if not math.isclose(
            self.hitl_rate,
            self.hitl_trials / self.trials,
            rel_tol=0,
            abs_tol=1e-12,
        ):
            raise ValueError("HITL rate does not match hitl_trials/trials")
        if (
            any(
                value is not None
                for value in (
                    self.total_tokens,
                    self.mean_tokens_per_trial,
                    self.estimated_cost,
                    self.cost_currency,
                )
            )
            or self.token_coverage != 0
            or self.cost_coverage != 0
        ):
            raise ValueError("the deterministic component harness cannot claim token or cost data")
        return self


class AgentAblationReport(_StrictModel):
    report_type: Literal["multi_agent_ablation"] = "multi_agent_ablation"
    protocol_id: Literal["creditlens_multi_agent_ablation_v1"]
    protocol_version: Literal["1.0.0"]
    dataset_sha256: str
    observations_sha256: str
    observation_set_id: str
    git_commit: str = Field(pattern=r"^[0-9a-f]{7,64}$")
    git_dirty: bool
    source_state_sha256: str
    source_state_algorithm: Literal["sha256-canonical-file-manifest-v1"]
    source_state_scope: Literal["creditlens-runtime-evidence-v1"]
    source_state_file_count: int = Field(gt=0)
    evidence_maturity: EvidenceMaturity
    comparison_valid: Literal[True] = True
    comparison_scope: Literal["WITHIN_DETERMINISTIC_COMPONENT_HARNESS"] = (
        "WITHIN_DETERMINISTIC_COMPONENT_HARNESS"
    )
    artifact_verification: Literal[
        "ALL_SIDECARS_SCHEMA_SHA256_AND_PRIMITIVE_RECOMPUTATION_VERIFIED"
    ] = "ALL_SIDECARS_SCHEMA_SHA256_AND_PRIMITIVE_RECOMPUTATION_VERIFIED"
    limitations: list[str] = Field(min_length=1)
    metrics: list[AblationVariantMetrics] = Field(min_length=4, max_length=4)

    @field_validator("dataset_sha256", "observations_sha256")
    @classmethod
    def validate_report_hashes(cls, value: str) -> str:
        normalized = value.strip().lower()
        if len(normalized) != 64 or any(
            character not in "0123456789abcdef" for character in normalized
        ):
            raise ValueError("report hashes must be lowercase SHA-256 digests")
        return normalized

    @model_validator(mode="after")
    def validate_complete_comparison(self) -> Self:
        validate_source_state_binding(
            git_commit=self.git_commit,
            git_dirty=self.git_dirty,
            source_state_sha256=self.source_state_sha256,
            source_state_algorithm=self.source_state_algorithm,
            source_state_scope=self.source_state_scope,
            source_state_file_count=self.source_state_file_count,
            evidence_maturity=self.evidence_maturity,
        )
        variants = [item.variant for item in self.metrics]
        if len(set(variants)) != len(variants) or set(variants) != set(AblationVariant):
            raise ValueError("ablation report requires exactly one metric for every frozen variant")
        if any(item.trials != 6 for item in self.metrics):
            raise ValueError("every frozen ablation variant requires exactly six trials")
        if any(item.unsupported_claims_emitted != 3 for item in self.metrics):
            raise ValueError("every frozen variant requires exactly three unsupported-claim trials")
        if any(item.counter_evidence_targets != 2 for item in self.metrics):
            raise ValueError("every frozen variant requires exactly two counter-evidence targets")
        if self.limitations != HARNESS_LIMITATIONS:
            raise ValueError("ablation report limitations must match the frozen harness scope")
        return self


def _resolve_artifact_path(artifact_root: Path, relative_path: str) -> Path:
    root = artifact_root.resolve()
    resolved = (root / Path(*PurePosixPath(relative_path).parts)).resolve()
    if not resolved.is_relative_to(root):
        raise ValueError("artifact sidecar path escapes artifact_root")
    return resolved


def verify_observation_artifacts(
    observations: AgentAblationObservationSet,
    *,
    dataset: AgentAblationDataset,
    artifact_root: Path,
) -> None:
    """Fail closed unless every observation has an intact, correlated sidecar."""

    scenario_by_id = {item.scenario_id: item for item in dataset.scenarios}
    variant_by_name = {item.variant: item for item in dataset.variants}
    for observation in observations.observations:
        cell = f"{observation.scenario_id}/{observation.variant.value}"
        scenario = scenario_by_id.get(observation.scenario_id)
        definition = variant_by_name.get(observation.variant)
        if scenario is None or definition is None:
            raise ValueError(f"{cell}: sidecar cell is absent from the frozen dataset")
        path = _resolve_artifact_path(artifact_root, observation.source_artifact_path)
        try:
            payload = path.read_bytes()
        except OSError as exc:
            raise ValueError(f"{cell}: artifact sidecar is missing or unreadable: {path}") from exc
        actual_hash = hashlib.sha256(payload).hexdigest()
        if actual_hash != observation.source_artifact_sha256:
            raise ValueError(f"{cell}: artifact sidecar SHA-256 mismatch")
        try:
            sidecar = AblationHarnessArtifact.model_validate_json(payload)
        except ValueError as exc:
            raise ValueError(f"{cell}: artifact sidecar schema validation failed: {exc}") from exc
        if sidecar.collector_version != observations.metadata.collector_version:
            raise ValueError(f"{cell}: sidecar collector_version does not match metadata")
        if sidecar.limitations != HARNESS_LIMITATIONS:
            raise ValueError(f"{cell}: sidecar limitations do not match the protocol")
        _recompute_and_verify_sidecar(
            sidecar,
            scenario=scenario,
            definition=definition,
            cell=cell,
        )
        correlated = {
            "scenario_id": (sidecar.scenario_id, observation.scenario_id),
            "variant": (sidecar.variant, observation.variant),
            "execution_semantics": (
                sidecar.execution_semantics,
                observation.execution_semantics,
            ),
            "source_run_id": (sidecar.source_run_id, observation.source_run_id),
            "recorded_at": (sidecar.recorded_at, observation.recorded_at),
            "unsupported_claim_ids_emitted": (
                sidecar.outcome.unsupported_claim_ids_emitted,
                observation.unsupported_claim_ids_emitted,
            ),
            "unsupported_claim_ids_intercepted": (
                sidecar.outcome.unsupported_claim_ids_intercepted,
                observation.unsupported_claim_ids_intercepted,
            ),
            "counter_evidence_target_ids_found": (
                sidecar.outcome.counter_evidence_target_ids_found,
                observation.counter_evidence_target_ids_found,
            ),
            "hitl_triggered": (
                sidecar.outcome.hitl_triggered,
                observation.hitl_triggered,
            ),
            "terminal_status": (
                sidecar.outcome.terminal_status,
                observation.terminal_status,
            ),
            "latency_ms": (sidecar.measured_latency_ms, observation.latency_ms),
            "total_tokens": (sidecar.total_tokens, observation.total_tokens),
            "estimated_cost": (sidecar.estimated_cost, observation.estimated_cost),
            "cost_currency": (sidecar.cost_currency, observation.cost_currency),
        }
        mismatches = [name for name, (actual, expected) in correlated.items() if actual != expected]
        if mismatches:
            raise ValueError(f"{cell}: sidecar/observation mismatch for {mismatches}")


def _recompute_and_verify_sidecar(
    sidecar: AblationHarnessArtifact,
    *,
    scenario: AblationScenario,
    definition: AblationVariantDefinition,
    cell: str,
) -> None:
    """Re-run production primitives from frozen inputs instead of trusting labels."""

    fixture = scenario.component_harness
    if sidecar.disabled_components != definition.disabled_components:
        raise ValueError(f"{cell}: disabled_components do not match the frozen variant")
    expected_challenger_enabled = "challenger" not in definition.disabled_components
    expected_auditor_enabled = "auditor" not in definition.disabled_components
    if sidecar.challenger_enabled != expected_challenger_enabled:
        raise ValueError(f"{cell}: Challenger enablement does not match the frozen variant")
    if sidecar.auditor_enabled != expected_auditor_enabled:
        raise ValueError(f"{cell}: Auditor enablement does not match the frozen variant")

    input_artifact = sidecar.input_artifact
    expected_input_hash = hashlib.sha256(fixture.model_dump_json().encode("utf-8")).hexdigest()
    if input_artifact.input_hash != expected_input_hash:
        raise ValueError(f"{cell}: input_hash does not match the frozen fixture")
    if input_artifact.task_id != f"ablation:{scenario.scenario_id}":
        raise ValueError(f"{cell}: input task_id does not match the frozen scenario")
    if input_artifact.producer != "deterministic_component_harness":
        raise ValueError(f"{cell}: input producer is not the component harness")
    if len(input_artifact.claims) != 1:
        raise ValueError(f"{cell}: component harness requires exactly one input claim")
    claim = input_artifact.claims[0]
    expected_claim = (
        fixture.claim_statement,
        fixture.claim_category,
        fixture.as_of_date,
        "SUPPORTED",
    )
    actual_claim = (claim.statement, claim.category, claim.as_of_date, claim.verdict)
    if actual_claim != expected_claim:
        raise ValueError(f"{cell}: input claim does not match the frozen fixture")
    if len(claim.supporting_evidence_ids) != 1:
        raise ValueError(f"{cell}: frozen input claim requires one evidence reference")
    if fixture.evidence_mode == HarnessEvidenceMode.UNKNOWN_REFERENCE:
        if input_artifact.evidence:
            raise ValueError(f"{cell}: UNKNOWN_REFERENCE fixture must omit evidence")
    else:
        if len(input_artifact.evidence) != 1:
            raise ValueError(f"{cell}: frozen fixture requires exactly one evidence object")
        evidence = input_artifact.evidence[0]
        if evidence.evidence_type != fixture.evidence_mode.value:
            raise ValueError(f"{cell}: evidence type does not match evidence_mode")
        if claim.supporting_evidence_ids != [evidence.evidence_id]:
            raise ValueError(f"{cell}: claim/evidence binding does not match the fixture")

    if expected_auditor_enabled:
        recomputed_validation = validate_artifact_contract(
            input_artifact,
            fixture.as_of_date,
        )
        expected_validation = (
            True,
            True,
            True,
            recomputed_validation.ok,
            recomputed_validation.violations,
        )
    else:
        expected_validation = (False, False, False, None, [])
    actual_validation = (
        sidecar.contract_validation.component_enabled,
        sidecar.contract_validation.executed,
        sidecar.contract_validation.enforced,
        sidecar.contract_validation.ok,
        sidecar.contract_validation.violations,
    )
    if actual_validation != expected_validation:
        raise ValueError(f"{cell}: contract validation trace does not match recomputation")
    expected_intercepted = []
    if expected_auditor_enabled:
        expected_intercepted = [
            label
            for label, expected_fragment in (fixture.expected_contract_violation_substrings.items())
            if any(
                expected_fragment in violation
                for violation in sidecar.contract_validation.violations
            )
        ]
    if sidecar.outcome.unsupported_claim_ids_emitted != scenario.unsupported_claim_ids:
        raise ValueError(f"{cell}: emitted labels do not match the frozen injection")
    if sidecar.outcome.unsupported_claim_ids_intercepted != expected_intercepted:
        raise ValueError(f"{cell}: intercepted labels do not match contract recomputation")

    expected_assessments = fixture.counter_evidence if expected_challenger_enabled else []
    if len(sidecar.conflict_assessments) != len(expected_assessments):
        raise ValueError(f"{cell}: conflict assessment count does not match the frozen fixture")
    for trace, expected in zip(
        sidecar.conflict_assessments,
        expected_assessments,
        strict=True,
    ):
        is_conflict, reason = assess_conflict(fixture.claim_statement, expected.text)
        if expected.expected_conflict != is_conflict:
            raise ValueError(
                f"{cell}: frozen expected_conflict disagrees with production recomputation"
            )
        expected_trace = (
            expected.target_id,
            fixture.claim_statement,
            expected.text,
            expected.expected_conflict,
            is_conflict,
            reason,
        )
        actual_trace = (
            trace.target_id,
            trace.claim_text,
            trace.counter_text,
            trace.expected_conflict,
            trace.is_conflict,
            trace.reason,
        )
        if actual_trace != expected_trace:
            raise ValueError(f"{cell}: conflict trace does not match production recomputation")
    expected_found = [item.target_id for item in expected_assessments]
    if sidecar.outcome.counter_evidence_target_ids_found != expected_found:
        raise ValueError(f"{cell}: counter-evidence labels do not match recomputation")


def _nearest_rank_p95(values: list[float]) -> float:
    ordered = sorted(values)
    rank = max(1, math.ceil(0.95 * len(ordered)))
    return ordered[rank - 1]


def evaluate_agent_ablation(
    dataset: AgentAblationDataset,
    observations: AgentAblationObservationSet,
    *,
    dataset_sha256: str,
    observations_sha256: str,
    artifact_root: Path,
) -> AgentAblationReport:
    """Validate the complete evidence matrix and calculate comparable metrics."""

    if observations.protocol_id != dataset.protocol_id:
        raise ValueError("observation protocol_id does not match the dataset")
    if observations.protocol_version != dataset.protocol_version:
        raise ValueError("observation protocol_version does not match the dataset")
    if observations.metadata.dataset_sha256 != dataset_sha256:
        raise ValueError("observation metadata dataset_sha256 does not match scored bytes")
    verify_observation_artifacts(
        observations,
        dataset=dataset,
        artifact_root=artifact_root,
    )

    scenario_by_id = {item.scenario_id: item for item in dataset.scenarios}
    variant_by_name = {item.variant: item for item in dataset.variants}
    expected_cells = {
        (scenario.scenario_id, variant.variant)
        for scenario in dataset.scenarios
        for variant in dataset.variants
    }
    actual_cells = {(item.scenario_id, item.variant) for item in observations.observations}
    if actual_cells != expected_cells:
        missing = sorted(
            f"{scenario}/{variant}" for scenario, variant in expected_cells - actual_cells
        )
        unexpected = sorted(
            f"{scenario}/{variant}" for scenario, variant in actual_cells - expected_cells
        )
        raise ValueError(f"incomplete ablation matrix; missing={missing}, unexpected={unexpected}")

    grouped: dict[AblationVariant, list[AblationTrialObservation]] = defaultdict(list)
    for item in observations.observations:
        scenario = scenario_by_id[item.scenario_id]
        definition = variant_by_name[item.variant]
        if item.execution_semantics != definition.execution_semantics:
            raise ValueError(
                f"{item.scenario_id}/{item.variant}: execution_semantics does not match protocol"
            )
        allowed_unsupported = set(scenario.unsupported_claim_ids)
        if set(item.unsupported_claim_ids_emitted) != allowed_unsupported:
            raise ValueError(
                f"{item.scenario_id}: emitted unsupported labels must exactly match the "
                "frozen injection labels"
            )
        if not set(item.counter_evidence_target_ids_found) <= set(
            scenario.counter_evidence_target_ids
        ):
            raise ValueError(f"{item.scenario_id}: unknown counter-evidence target label")
        grouped[item.variant].append(item)

    metrics: list[AblationVariantMetrics] = []
    for variant in AblationVariant:
        trials = grouped[variant]
        emitted = sum(len(item.unsupported_claim_ids_emitted) for item in trials)
        intercepted = sum(len(item.unsupported_claim_ids_intercepted) for item in trials)
        counter_targets = sum(
            len(scenario_by_id[item.scenario_id].counter_evidence_target_ids) for item in trials
        )
        counter_found = sum(len(item.counter_evidence_target_ids_found) for item in trials)
        token_values = [item.total_tokens for item in trials if item.total_tokens is not None]
        cost_values = [item.estimated_cost for item in trials if item.estimated_cost is not None]
        currencies = {item.cost_currency for item in trials if item.cost_currency is not None}
        if len(currencies) > 1:
            raise ValueError(f"{variant}: mixed cost currencies are not comparable")
        metrics.append(
            AblationVariantMetrics(
                variant=variant,
                execution_semantics=variant_by_name[variant].execution_semantics,
                trials=len(trials),
                unsupported_claims_emitted=emitted,
                unsupported_claims_intercepted=intercepted,
                unsupported_claim_interception_rate=(intercepted / emitted if emitted else None),
                counter_evidence_targets=counter_targets,
                counter_evidence_targets_found=counter_found,
                counter_evidence_recall=(
                    counter_found / counter_targets if counter_targets else None
                ),
                hitl_trials=sum(item.hitl_triggered for item in trials),
                hitl_rate=sum(item.hitl_triggered for item in trials) / len(trials),
                p95_latency_ms=_nearest_rank_p95([item.latency_ms for item in trials]),
                total_tokens=sum(token_values) if len(token_values) == len(trials) else None,
                mean_tokens_per_trial=(
                    sum(token_values) / len(token_values)
                    if len(token_values) == len(trials)
                    else None
                ),
                token_coverage=len(token_values) / len(trials),
                estimated_cost=(
                    sum(cost_values, start=Decimal("0"))
                    if len(cost_values) == len(trials)
                    else None
                ),
                cost_currency=next(iter(currencies)) if len(cost_values) == len(trials) else None,
                cost_coverage=len(cost_values) / len(trials),
            )
        )

    return AgentAblationReport(
        protocol_id=dataset.protocol_id,
        protocol_version=dataset.protocol_version,
        dataset_sha256=dataset_sha256,
        observations_sha256=observations_sha256,
        observation_set_id=observations.observation_set_id,
        git_commit=observations.metadata.git_commit,
        git_dirty=observations.metadata.git_dirty,
        source_state_sha256=observations.metadata.source_state_sha256,
        source_state_algorithm=observations.metadata.source_state_algorithm,
        source_state_scope=observations.metadata.source_state_scope,
        source_state_file_count=observations.metadata.source_state_file_count,
        evidence_maturity=observations.metadata.evidence_maturity,
        limitations=list(HARNESS_LIMITATIONS),
        metrics=metrics,
    )


