class ContractValidationTrace(_StrictModel):
    component_enabled: bool
    executed: bool
    enforced: bool
    ok: bool | None = None
    violations: list[str] = Field(default_factory=list)

    @model_validator(mode="after")
    def validate_execution_shape(self) -> Self:
        if self.component_enabled != self.executed or self.executed != self.enforced:
            raise ValueError(
                "contract validator must execute and enforce exactly when Auditor is enabled"
            )
        if self.executed and self.ok is None:
            raise ValueError("executed contract validation requires an ok result")
        if not self.executed and (self.ok is not None or self.violations):
            raise ValueError("disabled contract validation cannot expose results")
        return self


