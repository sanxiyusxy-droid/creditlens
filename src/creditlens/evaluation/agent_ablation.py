"""Strict, evidence-backed scoring for the v1.6 Multi-Agent ablation protocol.

The committed experiment is deliberately narrower than an online Supervisor run:
all four variants execute the same frozen, deterministic component harness.  This
makes their safety decisions comparable without pretending that a database, an
LLM, or the complete Agent graph ran.  Every scored cell is backed by a schema-
validated JSON sidecar whose bytes must match the observation SHA-256.
"""

